# Fallback advance for a codepoint the atlas has no glyph for: the
# rasterizer substitutes the visible U+FFFD replacement glyph.
_MISSING = EXTRA_ADVANCES[0xFFFD]


def advance(text: str, font_size: float) -> float:
    """Advance width in px of `text` rendered at `font_size`."""
    units = 0
    for char in text:
        code = ord(char)
        if FIRST <= code <= LAST:
            units += ASCII_ADVANCES[code - FIRST]
        else:
            units += EXTRA_ADVANCES.get(code, _MISSING)
    return font_size * units / BASE_PX
